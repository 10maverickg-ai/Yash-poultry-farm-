-- One row per bird movement a flock's day-to-day count doesn't explain by
-- mortality alone — a margin note on the register ("(-)2967", "740", "485"),
-- or a gap the bal-bird chain check finds with no margin note at all. Two
-- rows for a same-page transfer (one flock's transfer_out, the matching
-- flock's transfer_in), linked via counterpart_flock_id; one row for a sale,
-- a cull, a shift to/from Anil farm (counterpart_flock_id NULL — Anil farm
-- is a separate entity, not a row in `flocks` — named in `buyer` instead),
-- or a count_adjustment (the owner confirmed the written figure itself,
-- nothing actually moved). needs_review=true + reviewed_by_owner=false is
-- the open queue the review screen lists; the owner's one-tap answer (or the
-- reader's own confident pairing) resolves it.
CREATE TABLE flock_movements (
    id                   bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    farm_code            text NOT NULL DEFAULT 'YPF',
    date                 date NOT NULL,
    flock_internal_id    uuid NOT NULL REFERENCES flocks(flock_internal_id),
    -- Signed: negative = birds left this flock, positive = birds arrived.
    birds_change         integer NOT NULL CHECK (birds_change <> 0),
    movement_type        text NOT NULL CHECK (movement_type IN (
                             'transfer_out', 'transfer_in', 'sale', 'cull',
                             'unexplained_out', 'unexplained_in', 'count_adjustment'
                         )),
    -- Set only for a same-page transfer paired with another flock's own
    -- movement row; NULL for a sale, cull, Anil-farm shift, or anything
    -- still unexplained.
    counterpart_flock_id uuid REFERENCES flocks(flock_internal_id),
    -- The owner's plain-words explanation once resolved (e.g. "Shifted to
    -- Anil farm to fill cages (owner confirmed)"). NULL while unresolved.
    reason                text,
    -- Free text naming who/where birds went for a sale or an Anil-farm
    -- shift — "Anil farm" is written here, not modeled as a flock, since it
    -- is a separate entity (see the ground rules: never a loss).
    buyer                text,
    price_per_bird        numeric,
    -- What was actually seen on the page (margin note text, or the chain
    -- evidence if there was no note at all) — kept even after resolution,
    -- as the audit trail for why this row exists.
    register_note          text,
    source                  text NOT NULL DEFAULT 'register bird-count chain',
    needs_review            boolean NOT NULL DEFAULT true,
    reviewed_by_owner       boolean NOT NULL DEFAULT false,
    created_at              timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX flock_movements_date_idx ON flock_movements (date);
CREATE INDEX flock_movements_flock_date_idx ON flock_movements (flock_internal_id, date);

-- The two "1 Chick" / "2 Chick" rows (left/right side of the chick shed —
-- kept separate so a rise in deaths is easy to localise, per the owner) plus
-- an optional third row for chicks transferred in from Anil farm.
-- row_position is a fixed 1/2/3 slot, not a free label, so the same side is
-- always the same column across days regardless of exactly how the model
-- read the row's handwritten label.
CREATE TABLE chick_daily_mortality (
    id                 bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    farm_code          text NOT NULL DEFAULT 'YPF',
    date               date NOT NULL,
    row_position       integer NOT NULL CHECK (row_position IN (1, 2, 3)),
    label_as_written   text NOT NULL,
    deaths             integer NOT NULL CHECK (deaths >= 0),
    chick_batch_note   text,
    source             text NOT NULL DEFAULT 'register photo, hand-entered',
    UNIQUE (farm_code, date, row_position)
);

COMMIT;
