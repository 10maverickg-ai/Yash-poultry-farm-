-- Migration 0045 (V12 N3): the medicine and vaccine register. One row per line written in the register (a medicine or vaccine given or
-- bought), for the whole farm, one flock or one shed. The cost is OPTIONAL: no cost means "cost not entered", never zero. Lines WITH
-- a cost flow into the Costs screen as category medicine / vaccine (lib/costs/load.ts). Additive only: a new table.
BEGIN;
CREATE TABLE IF NOT EXISTS medicine_lines (
    id                 bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    farm_code          text NOT NULL DEFAULT 'YPF',
    date               date NOT NULL,
    kind               text NOT NULL CHECK (kind IN ('medicine','vaccine')),
    item               text NOT NULL,
    scope              text NOT NULL DEFAULT 'farm' CHECK (scope IN ('farm','flock','shed')),
    flock_internal_id  uuid REFERENCES flocks(flock_internal_id),
    shed_code          text,
    quantity           numeric CHECK (quantity IS NULL OR quantity >= 0),
    unit               text,
    amount_inr         numeric CHECK (amount_inr IS NULL OR amount_inr >= 0),  -- NULL = cost not entered
    supplier           text,
    note               text,
    source_photo_url   text,          -- the register page photo (bucket register-photos, prefix medicines/)
    source_tag         text NOT NULL DEFAULT 'hand entry',  -- 'hand entry' | 'register import'
    created_at         timestamptz NOT NULL DEFAULT now(),
    updated_at         timestamptz NOT NULL DEFAULT now(),
    CHECK ((scope = 'flock') = (flock_internal_id IS NOT NULL)),
    CHECK ((scope = 'shed') = (shed_code IS NOT NULL))
);
CREATE INDEX IF NOT EXISTS medicine_lines_month_idx ON medicine_lines (farm_code, date);
COMMENT ON TABLE medicine_lines IS 'Medicine and vaccine register lines (V12). amount_inr NULL = cost not entered. Priced lines are counted as medicine/vaccine cost on the Costs screen.';
COMMIT;
