BEGIN;
CREATE TABLE IF NOT EXISTS vaccination_schedule (
    id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    farm_code         text NOT NULL DEFAULT 'YPF',
    flock_internal_id uuid REFERENCES flocks(flock_internal_id),
    chick_batch_id    bigint REFERENCES chick_batches(id),
    vaccine           text NOT NULL,
    due_date          date NOT NULL,
    given_date        date,
    route             text,
    note              text,
    source_entry_id   bigint REFERENCES knowledge_entries(id),
    created_at        timestamptz NOT NULL DEFAULT now(),
    CHECK (flock_internal_id IS NOT NULL OR chick_batch_id IS NOT NULL)
);
COMMIT;
