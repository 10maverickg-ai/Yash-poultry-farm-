-- Migration 0052 (V18 B3): actual average egg weights, for later. The farm does not weigh eggs yet, so FCR uses the BV300
-- standard egg weight for each flock's age. When a sample of eggs is weighed, one row per flock and day goes here and the
-- FCR uses it for that day and the 6 days after ("actual egg weight"), the standard otherwise. No entry screen yet.
-- Additive only: a new table. No row-level-security change (the same as every other table).
BEGIN;
CREATE TABLE IF NOT EXISTS egg_weight_samples (
    id                 bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    farm_code          text NOT NULL DEFAULT 'YPF',
    flock_internal_id  uuid NOT NULL REFERENCES flocks(flock_internal_id),
    date               date NOT NULL,
    avg_egg_weight_g   numeric NOT NULL CHECK (avg_egg_weight_g > 20 AND avg_egg_weight_g < 100),  -- grams per egg
    eggs_weighed       integer CHECK (eggs_weighed IS NULL OR eggs_weighed > 0),                   -- how many eggs were in the sample
    note               text,
    created_at         timestamptz NOT NULL DEFAULT now(),
    UNIQUE (farm_code, flock_internal_id, date)
);
COMMENT ON TABLE egg_weight_samples IS 'Average egg weight weighed on the farm (V18). FCR uses it for that flock on that day and the 6 days after; otherwise the BV300 standard egg weight for the flock''s age.';
COMMIT;
