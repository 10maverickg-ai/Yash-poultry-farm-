-- Migration 0035 (V6 G7): which monthly cost inputs the owner has dealt with.
-- 'none' = "nothing was bought this month" (diesel, medicines); 'confirmed' =
-- "the standing figure is right for this month" (labour, packing). Additive only.
BEGIN;
CREATE TABLE IF NOT EXISTS monthly_input_status (
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    farm_code  text NOT NULL DEFAULT 'YPF',
    month      text NOT NULL CHECK (month ~ '^\d{4}-\d{2}$'),
    input_key  text NOT NULL CHECK (input_key IN ('electricity','diesel','medicines','labour','packing')),
    status     text NOT NULL CHECK (status IN ('none','confirmed')),
    note       text,
    created_at timestamptz NOT NULL DEFAULT now(),
    UNIQUE (farm_code, month, input_key)
);
COMMIT;
