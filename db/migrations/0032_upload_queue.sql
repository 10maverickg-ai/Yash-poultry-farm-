-- Migration 0032 (V5 item 8.1): server-side upload queue. Additive only.
-- One row per photo; survives closing the browser. The photo itself is in the
-- register-photos storage bucket (photo_url), never overwritten.
BEGIN;
CREATE TABLE IF NOT EXISTS upload_queue (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    farm_code     text NOT NULL DEFAULT 'YPF',
    original_name text,
    photo_url     text NOT NULL,
    entered_date  date NOT NULL,          -- the date the owner said the page shows
    status        text NOT NULL DEFAULT 'waiting'
                  CHECK (status IN ('waiting','reading','saved','needs_review','failed','duplicate','dismissed')),
    replace_ok    boolean NOT NULL DEFAULT false,  -- owner chose "replace the saved day"
    force_date    date,                   -- owner's answer to a date-mismatch question
    page_date     date,                   -- date the reader saw on the page, if it differed
    attempts      integer NOT NULL DEFAULT 0,
    message       text,                   -- plain-language outcome / error shown to the owner
    detail        jsonb,                  -- summary of the reader outcome (flocks written, flags, ...)
    technical     text,                   -- technical detail, for reporting a bug
    reader        text,                   -- which reader handled it ('old')
    created_at    timestamptz NOT NULL DEFAULT now(),
    started_at    timestamptz,
    finished_at   timestamptz
);
CREATE INDEX IF NOT EXISTS upload_queue_status_idx ON upload_queue (farm_code, status, entered_date, id);
COMMIT;
