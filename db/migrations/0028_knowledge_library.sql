-- Migration 0028 (V5 item 1.2 / 6.1): knowledge library. Additive only.
-- Facts and short cited excerpts only; never long copyrighted text.
BEGIN;
CREATE TABLE IF NOT EXISTS knowledge_documents (
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company    text NOT NULL,
    title      text NOT NULL,
    year       integer,
    source_url text,
    doc_key    text NOT NULL UNIQUE,   -- stable key from the JSON file, for idempotent import
    created_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS knowledge_entries (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    document_id bigint NOT NULL REFERENCES knowledge_documents(id) ON DELETE CASCADE,
    entry_key   text NOT NULL,          -- stable key within the document
    topic       text NOT NULL,
    page        text,                   -- page / section
    breed       text,
    notes       text,
    created_at  timestamptz NOT NULL DEFAULT now(),
    UNIQUE (document_id, entry_key)
);
CREATE TABLE IF NOT EXISTS knowledge_standards (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    entry_id    bigint NOT NULL REFERENCES knowledge_entries(id) ON DELETE CASCADE,
    metric      text NOT NULL,          -- e.g. hen_day_percent, feed_g_per_bird_day, body_weight_g
    age_weeks   integer NOT NULL,
    value       numeric NOT NULL,
    unit        text,
    UNIQUE (entry_id, metric, age_weeks)
);
CREATE INDEX IF NOT EXISTS knowledge_entries_topic_idx ON knowledge_entries (topic);
COMMIT;
