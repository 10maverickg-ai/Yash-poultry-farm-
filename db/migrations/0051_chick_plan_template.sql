CREATE TABLE IF NOT EXISTS vaccination_schedule_template (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    farm_code     text NOT NULL DEFAULT 'YPF',
    day_from      integer NOT NULL CHECK (day_from >= 1),
    day_to        integer CHECK (day_to IS NULL OR day_to >= day_from),   -- NULL = that one day; a range such as day 18 to 20 is a window
    catalogue_id  bigint NOT NULL REFERENCES medicine_catalogue(id),
    note          text,
    sort_order    integer NOT NULL DEFAULT 0,
    active        boolean NOT NULL DEFAULT true,
    created_at    timestamptz NOT NULL DEFAULT now(),
    UNIQUE (farm_code, day_from, catalogue_id)
);
COMMENT ON TABLE vaccination_schedule_template IS 'The owner''s chick vaccination and management schedule by day of age (day 1 = arrival). V14.';

