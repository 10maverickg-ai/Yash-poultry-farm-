ALTER TABLE vaccination_schedule ADD COLUMN IF NOT EXISTS template_id  bigint REFERENCES vaccination_schedule_template(id);
ALTER TABLE vaccination_schedule ADD COLUMN IF NOT EXISTS window_end   date;   -- last day of a window such as day 18 to 20 (due_date is its first day)
CREATE INDEX IF NOT EXISTS vaccination_schedule_catalogue_idx ON vaccination_schedule (catalogue_id);
CREATE UNIQUE INDEX IF NOT EXISTS vaccination_schedule_plan_key ON vaccination_schedule (chick_batch_id, template_id) WHERE template_id IS NOT NULL AND chick_batch_id IS NOT NULL;

