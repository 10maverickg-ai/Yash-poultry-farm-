-- Migration 0027 (V5 item 1.2): cost settings and purchases. Additive only.
-- Bird sales are NOT a new table: flock_movements (type 'sale', price_per_bird).
BEGIN;
CREATE TABLE IF NOT EXISTS cost_settings (
    id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    farm_code      text NOT NULL DEFAULT 'YPF',
    cost_type      text NOT NULL,   -- feed_per_kg, electricity_month, labour_month, packing_per_tray, ...
    value          numeric NOT NULL,
    unit           text NOT NULL,   -- INR/kg, INR/month, INR/tray
    effective_from date NOT NULL,
    month          text,            -- 'YYYY-MM' for monthly entries (electricity)
    note           text,
    created_at     timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS cost_settings_type_idx ON cost_settings (farm_code, cost_type, effective_from);

CREATE TABLE IF NOT EXISTS purchases (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    farm_code    text NOT NULL DEFAULT 'YPF',
    date         date NOT NULL,
    category     text NOT NULL CHECK (category IN
                   ('feed_ingredient','chicks','packing','electricity','labour','medicine','vaccine','diesel','other')),
    item         text NOT NULL,
    quantity     numeric,
    unit         text,
    amount_inr   numeric NOT NULL CHECK (amount_inr >= 0),
    supplier     text,
    note         text,
    created_at   timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS purchases_date_idx ON purchases (farm_code, date);

CREATE TABLE IF NOT EXISTS diesel_purchases (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    farm_code   text NOT NULL DEFAULT 'YPF',
    date        date NOT NULL,
    litres      numeric NOT NULL CHECK (litres > 0),
    amount_inr  numeric NOT NULL CHECK (amount_inr >= 0),
    note        text,
    created_at  timestamptz NOT NULL DEFAULT now()
);
COMMIT;
