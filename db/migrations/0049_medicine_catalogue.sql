UPDATE medicine_lines m SET catalogue_id = c.id
  FROM medicine_catalogue c
 WHERE m.catalogue_id IS NULL AND c.farm_code = m.farm_code AND c.kind = m.kind AND lower(btrim(m.item)) = lower(btrim(c.name));
