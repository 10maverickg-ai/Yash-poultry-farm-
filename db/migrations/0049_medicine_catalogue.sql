-- Additive only: two new tables, new nullable columns on medicine_lines, a seed from the owner's own schedule. Nothing is deleted or changed
-- except medicine_lines.catalogue_id on lines whose typed name matches a list item exactly (live has no lines today).
-- The owner's words are kept as he wrote them. Nothing is invented: no doses, no brands he did not give. Items he marked "guess" are
-- created with needs_confirmation = true (the screen shows a "to confirm" badge).
BEGIN;

CREATE TABLE IF NOT EXISTS medicine_catalogue (
    id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    farm_code           text NOT NULL DEFAULT 'YPF',
    name                text NOT NULL CHECK (btrim(name) <> ''),
    kind                text NOT NULL CHECK (kind IN ('medicine','vaccine','management')),
    disease_or_purpose  text,
    route               text CHECK (route IS NULL OR route IN ('water','feed','injection','eye_drop','spray','wing_web','other')),
    usual_dose_text     text,
    brand               text,
    default_unit        text,
    active              boolean NOT NULL DEFAULT true,
    needs_confirmation  boolean NOT NULL DEFAULT false,
    note                text,
    created_at          timestamptz NOT NULL DEFAULT now(),
    updated_at          timestamptz NOT NULL DEFAULT now()
);
-- a name exists once (spelling and capital letters do not make a second item)
CREATE UNIQUE INDEX IF NOT EXISTS medicine_catalogue_name_key ON medicine_catalogue (farm_code, lower(btrim(name)));
COMMENT ON TABLE medicine_catalogue IS 'Master list of every medicine, vaccine and management task (V14). name is as the owner writes it. needs_confirmation = a guess or an unchecked spelling.';

CREATE TABLE IF NOT EXISTS medicine_aliases (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    farm_code     text NOT NULL DEFAULT 'YPF',
    catalogue_id  bigint NOT NULL REFERENCES medicine_catalogue(id) ON DELETE CASCADE,
    alias         text NOT NULL CHECK (btrim(alias) <> ''),
    created_at    timestamptz NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX IF NOT EXISTS medicine_aliases_alias_key ON medicine_aliases (farm_code, lower(btrim(alias)));
CREATE INDEX IF NOT EXISTS medicine_aliases_item_idx ON medicine_aliases (catalogue_id);
COMMENT ON TABLE medicine_aliases IS 'Other spellings of a list item (Croyza / Coryza). An alias can never equal another item''s name.';

-- An alias may not equal any item's name, and a name may not equal any alias of another item (so one word always means one item).
CREATE OR REPLACE FUNCTION medicine_alias_guard() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF TG_TABLE_NAME = 'medicine_aliases' THEN
    IF EXISTS (SELECT 1 FROM medicine_catalogue c WHERE c.farm_code = NEW.farm_code AND lower(btrim(c.name)) = lower(btrim(NEW.alias))) THEN
      RAISE EXCEPTION 'The spelling "%" is already the name of a list item.', NEW.alias USING ERRCODE = '23505';
    END IF;
  ELSE
    IF EXISTS (SELECT 1 FROM medicine_aliases a WHERE a.farm_code = NEW.farm_code AND a.catalogue_id <> NEW.id AND lower(btrim(a.alias)) = lower(btrim(NEW.name))) THEN
      RAISE EXCEPTION 'The name "%" is already another spelling of a different list item.', NEW.name USING ERRCODE = '23505';
    END IF;
  END IF;
  RETURN NEW;
END $$;
DROP TRIGGER IF EXISTS medicine_aliases_guard ON medicine_aliases;
CREATE TRIGGER medicine_aliases_guard BEFORE INSERT OR UPDATE ON medicine_aliases FOR EACH ROW EXECUTE FUNCTION medicine_alias_guard();
DROP TRIGGER IF EXISTS medicine_catalogue_guard ON medicine_catalogue;
CREATE TRIGGER medicine_catalogue_guard BEFORE INSERT OR UPDATE OF name ON medicine_catalogue FOR EACH ROW EXECUTE FUNCTION medicine_alias_guard();

