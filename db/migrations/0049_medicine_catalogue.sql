ALTER TABLE medicine_lines ADD COLUMN IF NOT EXISTS entry_group     text;           -- lines saved together (one entry for several flocks) share this
ALTER TABLE medicine_lines ADD COLUMN IF NOT EXISTS cost_total_inr  numeric CHECK (cost_total_inr IS NULL OR cost_total_inr >= 0);  -- the cost typed for the whole entry
ALTER TABLE medicine_lines ADD COLUMN IF NOT EXISTS quantity_total  numeric CHECK (quantity_total IS NULL OR quantity_total >= 0);  -- the quantity typed for the whole entry
ALTER TABLE medicine_lines ADD COLUMN IF NOT EXISTS split_basis     text CHECK (split_basis IS NULL OR split_basis IN ('birds','equal'));  -- how the totals were shared between the flocks
CREATE INDEX IF NOT EXISTS medicine_lines_catalogue_idx ON medicine_lines (catalogue_id);
CREATE INDEX IF NOT EXISTS medicine_lines_group_idx ON medicine_lines (entry_group) WHERE entry_group IS NOT NULL;

