-- Migration 0034 (V6 G3): the owner's verdict on each alert ("this was real" /
-- "this was noise"), so alert rules can be tuned from evidence. Additive only.
-- alert_key = '<rule>|<date>|<flock id or farm>' (stable; see engine.ts alertKey).
BEGIN;
CREATE TABLE IF NOT EXISTS alert_feedback (
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    farm_code  text NOT NULL DEFAULT 'YPF',
    alert_key  text NOT NULL,
    verdict    text NOT NULL CHECK (verdict IN ('real', 'noise')),
    note       text,
    created_at timestamptz NOT NULL DEFAULT now(),
    UNIQUE (farm_code, alert_key)
);
COMMIT;
