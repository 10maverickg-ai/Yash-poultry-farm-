-- Migration 0037 (V8 S0.5): when a flock was moved between segments. The engine
-- reads this so history keeps the old segment and alerts re-evaluate from the
-- move date. Additive only.
BEGIN;
CREATE TABLE IF NOT EXISTS flock_segment_history (
    id                 bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    flock_internal_id  uuid NOT NULL REFERENCES flocks(flock_internal_id),
    segment            text NOT NULL CHECK (segment IN ('main','young')),
    effective_from     date NOT NULL,
    created_at         timestamptz NOT NULL DEFAULT now(),
    UNIQUE (flock_internal_id, effective_from)
);
COMMIT;
