-- Migration 0042 (V10): (1) owner overrides for the realistic target, per group, metric and 5-week age band;
-- (2) a source tag on daily_production so days imported from old paper registers are recognisable. Additive only.
BEGIN;
CREATE TABLE IF NOT EXISTS realistic_target_overrides (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    farm_code   text NOT NULL DEFAULT 'YPF',
    grp         text NOT NULL CHECK (grp IN ('main','young')),
    metric      text NOT NULL CHECK (metric IN ('hd','feed','mortality')),
    band_start  integer NOT NULL CHECK (band_start >= 0),   -- first age week of the 5-week band
    ratio_pct   numeric(6,2) NOT NULL CHECK (ratio_pct > 0), -- "our realistic level = ratio_pct % of the breeder's book"
    note        text,
    created_at  timestamptz NOT NULL DEFAULT now(),
    UNIQUE (farm_code, grp, metric, band_start)
);
ALTER TABLE daily_production ADD COLUMN IF NOT EXISTS source_tag text;
COMMIT;
