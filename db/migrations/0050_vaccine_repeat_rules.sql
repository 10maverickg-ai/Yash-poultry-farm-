-- Migration 0050 (V14 Q5): vaccines that repeat (boosters). A rule says "this vaccine is repeated every N months for all laying flocks";
-- vaccine_repeat_rule_items lists which list items count towards the rule (any ND product counts as the ND booster once the owner ticks it).
-- Seeded with the two the owner named: ND booster and LPAI booster, every 6 months. Additive only. No last dates are invented: a flock with no
-- recorded booster shows "last date not entered".
BEGIN;
CREATE TABLE IF NOT EXISTS vaccine_repeat_rules (
    id                 bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    farm_code          text NOT NULL DEFAULT 'YPF',
    code               text NOT NULL,                       -- 'nd' | 'lpai'
    label              text NOT NULL,                       -- "ND booster"
    repeat_months      integer NOT NULL DEFAULT 6 CHECK (repeat_months BETWEEN 1 AND 60),
    applies_to         text NOT NULL DEFAULT 'laying_flocks' CHECK (applies_to IN ('laying_flocks')),
    main_catalogue_id  bigint REFERENCES medicine_catalogue(id),   -- the item "enter last date" records
    active             boolean NOT NULL DEFAULT true,
    created_at         timestamptz NOT NULL DEFAULT now(),
    UNIQUE (farm_code, code)
);
CREATE TABLE IF NOT EXISTS vaccine_repeat_rule_items (
    rule_id       bigint NOT NULL REFERENCES vaccine_repeat_rules(id) ON DELETE CASCADE,
    catalogue_id  bigint NOT NULL REFERENCES medicine_catalogue(id),
    PRIMARY KEY (rule_id, catalogue_id)
);
COMMENT ON TABLE vaccine_repeat_rules IS 'Vaccines repeated every N months for all laying flocks (V14). Next due = last given + N calendar months.';

INSERT INTO vaccine_repeat_rules (code, label, repeat_months, main_catalogue_id)
SELECT v.code, v.label, 6, c.id FROM (VALUES ('nd', 'ND booster', 'ND booster (lay)'), ('lpai', 'LPAI booster', 'LPAI booster (lay)')) AS v(code, label, item)
  JOIN medicine_catalogue c ON c.farm_code = 'YPF' AND lower(btrim(c.name)) = lower(v.item)
ON CONFLICT (farm_code, code) DO NOTHING;
INSERT INTO vaccine_repeat_rule_items (rule_id, catalogue_id)
SELECT r.id, r.main_catalogue_id FROM vaccine_repeat_rules r WHERE r.main_catalogue_id IS NOT NULL
ON CONFLICT DO NOTHING;
COMMIT;
